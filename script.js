// Function Seenaa Banu fi Cufu (Toggle About Me)
function toggleAbout() {
  const aboutCard = document.getElementById("about-card");
  const toggleBtn = document.getElementById("toggle-about-btn");

  if (aboutCard.style.display === "none") {
    aboutCard.style.display = "block";
    toggleBtn.innerText = "✖ Cufi / Close";
  } else {
    aboutCard.style.display = "none";
    toggleBtn.innerText = "📖 Seenaa Koo Dubbisi / Read More";
  }
}
